					<h2>What is Stud Welding?</h2>
					<p>Stud welding is the process of joining a metal stud or fastener to the
						base of a metal surface via an electric arc. It is a single-side fastening
						process in which the electric arc melts the stud tip and a small area of
						the metal surface. The gun forces the melted stud into the molten pool
						of the surface, fusing them almost instantly.</p>

